export function articleForLevel(live = [], library = fallbackLibrary, level = "B1") {
  const readable = (article) => Boolean(article?.id && article.paragraphs?.length);
  const pool = (live || []).filter(readable);
  const exact = pool.find((article) => article.cefr === level);
  if (exact) return { article: exact, injected: false };
  const shelf = (library || []).find((article) => readable(article) && article.cefr === level);
  if (shelf) return { article: shelf, injected: true };
  const shell = (live || []).find((article) => article?.id && article.cefr === level);
  if (shell) return { article: shell, injected: false };
  return { article: pool[0] ?? null, injected: false };
}

